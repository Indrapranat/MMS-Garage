// Helper untuk menghasilkan daftar rekomendasi pengadaan (stok <= ROP)
export function getInitialRecommendations(): RecommendationItem[] {
  return initialEoqRopData
    .filter((item) => item.stokSaatIni <= item.rop)
    .map((item) => {
      const isCritical = item.stokSaatIni <= item.safetyStock;
      const hargaPerUnit = item.rekomendasiPesanQty > 0 
        ? Math.round(item.estimasiBiayaPengadaan / item.rekomendasiPesanQty)
        : 85000;
      return {
        id: `rec-${item.id}`,
        sparepartId: item.id,
        kode: item.kode,
        namaSparepart: item.namaSparepart,
        kategori: item.kategori,
        stokSaatIni: item.stokSaatIni,
        rop: item.rop,
        eoq: item.eoq,
        status: isCritical ? "Kritis" : "Perlu Pemesanan",
        jumlahRekomendasiPemesanan: item.eoq,
        supplierId: "sup-1",
        supplierNama: item.supplierNama,
        supplierTelepon: "0812-3456-7890",
        leadTimeHari: item.supplierLeadTime,
        hargaBeliSatuan: hargaPerUnit,
        estimasiTotalBiaya: item.estimasiBiayaPengadaan,
        catatanKebutuhan: `Stok saat ini ${item.stokSaatIni} unit telah berada di bawah batas ROP (${item.rop} unit). Segera lakukan PO sejumlah EOQ (${item.eoq} unit).`,
        terakhirDipesan: "2026-08-20",
      };
    });
}
